// 仕様 (design-docs/tower-like-game/15-balance-v1.5.0.md §0-3, §1.2):
// 発動率 p (0〜∞、100% を超えて青天井) を「確定回数 + 端数確率で +1」の
// 整数回数に変換する。 期待値は常に p で連続 (100% 跨ぎで段差が出ない)。
//
// 例: p = 1.5 → floor(1.5) = 1 確定 + 50% で +1 → 期待値 1.5
//     p = 0   → 0 回 (常に不発)
//     p = 2.0 → 2 回確定 (端数 0 なので rng を消費しない)

/**
 * p (0〜∞) を「floor(p) + 端数確率で +1」の整数回数に変換する。
 * 期待値は常に p。
 *
 * @param p   発動率 (100% = 1.0 換算。上限なし、負値は 0 として扱う)
 * @param rng 0〜1 の乱数生成関数
 */
export function rollOverflowCount(p: number, rng: () => number): number {
  if (p <= 0) return 0;
  const floor = Math.floor(p);
  const frac = p - floor;
  return frac > 0 && rng() < frac ? floor + 1 : floor;
}
